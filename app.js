async function checkout(
  event
) {

  event.preventDefault();


  if (!cart.length) {

    toast(
      t().addBefore
    );

    return;

  }


  /*
   * EUA
   *
   * PayPal/Venmo usam seus próprios botões.
   */

  if (
    country === 'us'
  ) {

    initializePayPalCheckout();

    return;

  }


  /*
   * BRASIL
   *
   * Continua pelo Mercado Pago.
   */

  if (!CONFIG.checkoutEndpoint) {

    toast(
      t().checkoutSetup
    );

    return;

  }


  const form =
    event.target;


  const data =
    new FormData(
      form
    );


  const items =

    cart
      .map(
        id => {

          const service =
            services.find(
              item =>
                item.id === id
            );


          if (!service) {
            return null;
          }


          const current =
            serviceData(
              service
            );


          return {

            id:
              service.id,

            title:
              current.title,

            quantity:
              1,

            unit_price:
              current.price

          };

        }
      )
      .filter(
        Boolean
      );


  if (!items.length) {

    toast(
      t().addBefore
    );

    return;

  }


  const payload = {

    country:
      'br',

    currency:
      'BRL',

    items,

    discount,


    customer: {

      name:
        data.get(
          'name'
        ),

      email:
        data.get(
          'email'
        ),

      phone:
        data.get(
          'phone'
        )

    },


    paymentMethod:
      data.get(
        'payment'
      )

  };


  const button =
    form.querySelector(
      'button[type="submit"]'
    );


  if (button) {

    button.disabled =
      true;

  }


  try {

    const response =
      await fetch(
        CONFIG.checkoutEndpoint,
        {

          method:
            'POST',

          headers: {

            'Content-Type':
              'application/json'

          },

          body:
            JSON.stringify(
              payload
            )

        }
      );


    const result =
      await response.json();


    if (!response.ok) {

      throw new Error(

        result?.details?.message ||

        result?.details?.error ||

        result?.error ||

        `Checkout request failed: ${response.status}`

      );

    }


    if (
      !result ||
      !result.init_point
    ) {

      throw new Error(
        'No Mercado Pago checkout URL returned.'
      );

    }


    window.location.href =
      result.init_point;


  } catch (
    error
  ) {

    console.error(
      'Checkout error:',
      error
    );


    toast(

      error.message ||

      (

        country === 'br'

          ? 'Não foi possível abrir o pagamento. Tente novamente.'

          : 'Unable to open payment. Please try again.'

      )

    );


  } finally {

    if (button) {

      button.disabled =
        false;

    }

  }

}


function setupReveal() {

  const elements =
    document.querySelectorAll(
      '.reveal-on-scroll'
    );


  if (
    !(
      'IntersectionObserver'
      in window
    )
  ) {

    elements.forEach(
      element =>
        element.classList.add(
          'is-visible'
        )
    );


    return;

  }


  const observer =
    new IntersectionObserver(

      entries => {

        entries.forEach(
          entry => {

            if (
              entry.isIntersecting
            ) {

              entry.target.classList.add(
                'is-visible'
              );


              observer.unobserve(
                entry.target
              );

            }

          }
        );

      },


      {
        threshold:
          0.14
      }

    );


  elements.forEach(
    element =>
      observer.observe(
        element
      )
  );

}


