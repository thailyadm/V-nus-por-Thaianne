function updateLanguage() {

  const tr =
    t();


  document.documentElement.lang =
    tr.lang;


  document.title =
    tr.title;


  const metaDescription =
    document.querySelector(
      'meta[name="description"]'
    );


  if (metaDescription) {

    metaDescription.content =
      tr.description;

  }


  document
    .querySelectorAll('[data-i18n]')
    .forEach(element => {

      const key =
        element.dataset.i18n;


      if (tr[key] !== undefined) {

        element.innerHTML =
          tr[key];

      }

    });


  document
    .querySelectorAll('[data-i18n-placeholder]')
    .forEach(element => {

      const key =
        element.dataset.i18nPlaceholder;


      if (tr[key] !== undefined) {

        element.placeholder =
          tr[key];

      }

    });


  const countrySelect =
    $('#countrySelect');


  if (countrySelect) {

    countrySelect.value =
      country;

  }


  updatePaymentOptions();

  renderServices();

  renderCart();

  updateWhatsAppLink();
}


function switchCountry(nextCountry) {

  if (
    nextCountry !== 'br' &&
    nextCountry !== 'us'
  ) {
    return;
  }


  country =
    nextCountry;


  localStorage.setItem(
    'venusCountry',
    country
  );


  updateLanguage();
}


function renderServices() {

  const grid =
    $('#serviceGrid');


  if (!grid) return;


  grid.innerHTML =
    services
      .map(service => {

        const data =
          serviceData(service);


        return `

          <article class="service-card">

            <div class="service-icon">
              ${service.icon}
            </div>

            <p class="service-meta">
              ${data.meta}
            </p>

            <h3>
              ${data.title}
            </h3>

            <p>
              ${data.description}
            </p>

            <div class="service-footer">

              <span class="price">
                ${money(data.price)}
              </span>

              <button
                class="add-btn"
                data-id="${service.id}"
                type="button"
              >
                ${t().add}
              </button>

            </div>

          </article>

        `;

      })
      .join('');


  grid
    .querySelectorAll('.add-btn')
    .forEach(button => {

      button.addEventListener(
        'click',
        () =>
          addToCart(
            button.dataset.id
          )
      );

    });
}


function addToCart(id) {

  const service =
    services.find(
      item =>
        item.id === id
    );


  if (!service) return;


  /*
   * Permite várias consultas no carrinho.
   * O checkout dinâmico vai somar todas.
   */
  cart.push(id);


  persist();

  renderCart();


  toast(
    `${serviceData(service).title} ${t().added}`
  );


  openCart();
}


function removeFromCart(index) {

  if (
    index < 0 ||
    index >= cart.length
  ) {
    return;
  }


  cart.splice(
    index,
    1
  );


  persist();

  renderCart();
}


function persist() {

  localStorage.setItem(
    'venusCart',
    JSON.stringify(cart)
  );


  localStorage.setItem(
    'venusDiscount',
    String(discount)
  );
}


function subtotal() {

  return cart.reduce(
    (sum, id) => {

      const service =
        services.find(
          item =>
            item.id === id
        );


      return (
        sum +
        (
          service
            ? serviceData(service).price
            : 0
        )
      );

    },
    0
  );
}


function total() {

  return subtotal() *
    (1 - discount);
}


function renderCart() {

  const count =
    $('#cartCount');


  const items =
    $('#cartItems');


  const totalElement =
    $('#cartTotal');


  if (
    !count ||
    !items ||
    !totalElement
  ) {
    return;
  }


  count.textContent =
    cart.length;


  if (!cart.length) {

    items.innerHTML =
      `<p>${t().emptyCart}</p>`;

  } else {

    items.innerHTML =
      cart
        .map(
          (id, index) => {

            const service =
              services.find(
                item =>
                  item.id === id
              );


            if (!service) {
              return '';
            }


            const data =
              serviceData(service);


            return `

              <div class="cart-item">

                <div>

                  <h4>
                    ${data.title}
                  </h4>

                  <p>
                    ${data.meta}
                  </p>

                  <strong>
                    ${money(data.price)}
                  </strong>

                </div>

                <button
                  class="remove"
                  data-index="${index}"
                  type="button"
                >
                  ${t().remove}
                </button>

              </div>

            `;

          }
        )
        .filter(Boolean)
        .join('');

  }


  items
    .querySelectorAll('.remove')
    .forEach(button => {

      button.addEventListener(
        'click',
        () =>
          removeFromCart(
            Number(
              button.dataset.index
            )
          )
      );

    });


  totalElement.textContent =
    money(total());
}


function applyCoupon() {

  const input =
    $('#couponInput');


  const message =
    $('#couponMessage');


  if (
    !input ||
    !message
  ) {
    return;
  }


  const code =
    input.value
      .trim()
      .toUpperCase();


  if (
    code &&
    CONFIG.coupons[code]
  ) {

    discount =
      CONFIG.coupons[code];


    message.textContent =
      `${t().couponApplied}: ${Math.round(discount * 100)}%.`;

  } else {

    discount =
      0;


    message.textContent =
      code
        ? t().invalidCoupon
        : t().enterCoupon;

  }


  persist();

  renderCart();
}


function openCart() {

  const drawer =
    $('#cartDrawer');

  const backdrop =
    $('#drawerBackdrop');


  if (drawer) {

    drawer.classList.add(
      'open'
    );

  }


  if (backdrop) {

    backdrop.classList.add(
      'show'
    );

  }
}


function closeCart() {

  const drawer =
    $('#cartDrawer');

  const backdrop =
    $('#drawerBackdrop');


  if (drawer) {

    drawer.classList.remove(
      'open'
    );

  }


  if (backdrop) {

    backdrop.classList.remove(
      'show'
    );

  }
}


function openCheckout() {

  if (!cart.length) {

    toast(
      t().addBefore
    );

    return;
  }


  closeCart();


  const modal =
    $('#checkoutModal');


  if (!modal) {
    return;
  }


  modal.classList.add(
    'show'
  );


  modal.setAttribute(
    'aria-hidden',
    'false'
  );


  renderCheckout();
}


function closeCheckout() {

  const modal =
    $('#checkoutModal');


  if (!modal) {
    return;
  }


  modal.classList.remove(
    'show'
  );


  modal.setAttribute(
    'aria-hidden',
    'true'
  );
}


function renderCheckout() {

  const summary =
    $('#checkoutSummary');


  if (!summary) {
    return;
  }


  summary.innerHTML = `

    <strong>
      ${t().summary}:
    </strong>

    <br>

    ${cart
      .map(id => {

        const service =
          services.find(
            item =>
              item.id === id
          );


        if (!service) {
          return '';
        }


        const data =
          serviceData(service);


        return `${data.title} — ${money(data.price)}`;

      })
      .filter(Boolean)
      .join('<br>')}

    <br><br>

    <strong>
      ${t().total}: ${money(total())}
    </strong>

  `;


  updatePaymentNote();
}

