async function initializePayPalCheckout() {
  if (
    paypalCheckoutInitialized
  ) {
    return;
  }

  const container =
    $('#paypal-button-container');

  const venmoContainer =
    $('#venmo-button-container');

  if (
    !container ||
    !venmoContainer
  ) {
    return;
  }

  try {
    await waitForPayPalSdk();

    paypalSdkInstance =
      await window.paypal.createInstance({
        clientId:
          CONFIG.paypalClientId,

        components: [
          'paypal-payments',
          'venmo-payments'
        ],

        pageType:
          'checkout',

        locale:
          'en-US'
      });

    const eligible =
      await paypalSdkInstance.findEligibleMethods(
        {
          currencyCode:
            'USD'
        }
      );

    container.innerHTML =
      '';

    venmoContainer.innerHTML =
      '';

    /*
     * PAYPAL
     */

    if (
      eligible.isEligible(
        'paypal'
      )
    ) {
      const paypalButton =
        document.createElement(
          'paypal-button'
        );

      paypalButton.setAttribute(
        'type',
        'button'
      );

      container.appendChild(
        paypalButton
      );

      const paymentSession =
        paypalSdkInstance
          .createPayPalOneTimePaymentSession({
            async onApprove(
              data
            ) {
              try {
                await capturePayPalOrder(
                  data.orderId
                );

                cart = [];
                discount = 0;

                persist();
                renderCart();
                showPaymentSuccess();
              } catch (
                error
              ) {
                console.error(
                  'PayPal capture error:',
                  error
                );

                toast(
                  error.message ||
                    'Payment could not be completed.'
                );
              }
            },

            onCancel(
              data
            ) {
              console.log(
                'PayPal payment cancelled:',
                data
              );
            },

            onError(
              error
            ) {
              console.error(
                'PayPal payment error:',
                error
              );

              toast(
                'PayPal payment error. Please try again.'
              );
            }
          });

      paypalButton.addEventListener(
        'click',
        async () => {
          try {
            await paymentSession.start(
              {
                presentationMode:
                  'auto'
              },

              createPayPalOrder()
            );
          } catch (
            error
          ) {
            console.error(
              'PayPal start error:',
              error
            );

            toast(
              error.message ||
                'Unable to start PayPal checkout.'
            );
          }
        }
      );
    }

    /*
     * VENMO
     */

    if (
      eligible.isEligible(
        'venmo'
      )
    ) {
      const venmoButton =
        document.createElement(
          'venmo-button'
        );

      venmoButton.setAttribute(
        'type',
        'pay'
      );

      venmoContainer.appendChild(
        venmoButton
      );

      const venmoPaymentSession =
        paypalSdkInstance
          .createVenmoOneTimePaymentSession({
            async onApprove(
              data
            ) {
              try {
                await capturePayPalOrder(
                  data.orderId
                );

                cart = [];
                discount = 0;

                persist();
                renderCart();
                showPaymentSuccess();
              } catch (
                error
              ) {
                console.error(
                  'Venmo capture error:',
                  error
                );

                toast(
                  error.message ||
                    'Venmo payment could not be completed.'
                );
              }
            },

            onCancel(
              data
            ) {
              console.log(
                'Venmo payment cancelled:',
                data
              );
            },

            onError(
              error
            ) {
              console.error(
                'Venmo payment error:',
                error
              );

              toast(
                'Venmo payment error. Please try again.'
              );
            }
          });

      venmoButton.addEventListener(
        'click',
        async () => {
          try {
            await venmoPaymentSession.start(
              {
                presentationMode:
                  'auto'
              },

              createPayPalOrder()
            );
          } catch (
            error
          ) {
            console.error(
              'Venmo start error:',
              error
            );

            toast(
              error.message ||
                'Unable to start Venmo.'
            );
          }
        }
      );
    }

    paypalCheckoutInitialized =
      true;
  } catch (
    error
  ) {
    console.error(
      'PayPal initialization error:',
      error
    );

    toast(
      'PayPal is temporarily unavailable. Please try again.'
    );
  }
}

async function checkout(
  event
) {
  event.preventDefault();

  if (!cart.length) {
    toast(
      t().addBefore
    );

    return;
  }

  /*
   * EUA
   *
   * PayPal/Venmo usam seus próprios botões.
   */

  if (
    country === 'us'
  ) {
    initializePayPalCheckout();

    return;
  }

  /*
   * BRASIL
   *
   * Continua pelo Mercado Pago.
   */

  if (!CONFIG.checkoutEndpoint) {
    toast(
      t().checkoutSetup
    );

    return;
  }

  const form =
    event.target;

  const data =
    new FormData(
      form
    );

  const items =
    cart
      .map(
        id => {
          const service =
            services.find(
              item =>
                item.id === id
            );

          if (!service) {
            return null;
          }

          const current =
            serviceData(
              service
            );

          return {
            id:
              service.id,

            title:
              current.title,

            quantity:
              1,

            unit_price:
              current.price
          };
        }
      )
      .filter(Boolean);

  if (!items.length) {
    toast(
      t().addBefore
    );

    return;
  }

  const payload = {
    country:
      'br',

    currency:
      'BRL',

    items,

    discount,

    customer: {
      name:
        data.get(
          'name'
        ),

      email:
        data.get(
          'email'
        ),

      phone:
        data.get(
          'phone'
        )
    },

    paymentMethod:
      data.get(
        'payment'
      )
  };

  const button =
    form.querySelector(
      'button[type="submit"]'
    );

  if (button) {
    button.disabled =
      true;
  }

  try {
    const response =
      await fetch(
        CONFIG.checkoutEndpoint,
        {
          method:
            'POST',

          headers: {
            'Content-Type':
              'application/json'
          },

          body:
            JSON.stringify(
              payload
            )
        }
      );

    const result =
      await response.json();

    if (!response.ok) {
      throw new Error(
        result?.details?.message ||
          result?.details?.error ||
          result?.error ||
          `Checkout request failed: ${response.status}`
      );
    }

    if (
      !result ||
      !result.init_point
    ) {
      throw new Error(
        'No Mercado Pago checkout URL returned.'
      );
    }

    window.location.href =
      result.init_point;
  } catch (
    error
  ) {
    console.error(
      'Checkout error:',
      error
    );

    toast(
      error.message ||
        (
          country === 'br'
            ? 'Não foi possível abrir o pagamento. Tente novamente.'
            : 'Unable to open payment. Please try again.'
        )
    );
  } finally {
    if (button) {
      button.disabled =
        false;
    }
  }
}
function setupReveal() {
  const elements =
    document.querySelectorAll(
      '.reveal-on-scroll'
    );

  if (
    !(
      'IntersectionObserver'
      in window
    )
  ) {
    elements.forEach(
      element =>
        element.classList.add(
          'is-visible'
        )
    );

    return;
  }

  const observer =
    new IntersectionObserver(
      entries => {
        entries.forEach(
          entry => {
            if (
              entry.isIntersecting
            ) {
              entry.target.classList.add(
                'is-visible'
              );

              observer.unobserve(
                entry.target
              );
            }
          }
        );
      },
      {
        threshold: 0.14
      }
    );

  elements.forEach(
    element =>
      observer.observe(
        element
      )
  );
}

function setupBackToTop() {
  const button =
    $('#backToTop');

  if (!button) {
    return;
  }

  const onScroll =
    () => {
      if (
        window.scrollY > 420
      ) {
        button.classList.add(
          'show'
        );
      } else {
        button.classList.remove(
          'show'
        );
      }
    };

  window.addEventListener(
    'scroll',
    onScroll,
    {
      passive: true
    }
  );

  button.addEventListener(
    'click',
    () => {
      window.scrollTo(
        {
          top: 0,
          behavior: 'smooth'
        }
      );
    }
  );

  onScroll();
}

