let country =
  localStorage.getItem(
    'venusCountry'
  ) || 'br';


let cart = [];


try {

  const savedCart =
    JSON.parse(
      localStorage.getItem(
        'venusCart'
      ) || '[]'
    );


  if (Array.isArray(savedCart)) {

    cart =
      savedCart
        .map(
          item =>
            typeof item === 'string'
              ? item
              : item?.id
        )
        .filter(Boolean);

  }

} catch {

  cart = [];

}


let discount =
  Number(
    localStorage.getItem(
      'venusDiscount'
    ) || 0
  );


const $ =
  selector =>
    document.querySelector(
      selector
    );


const t =
  () =>
    I18N[country];


const serviceData =
  service =>
    service[country];


const money =
  value =>
    new Intl.NumberFormat(
      t().locale,
      {
        style:
          'currency',

        currency:
          t().currency
      }
    ).format(
      value
    );


function persist() {

  localStorage.setItem(
    'venusCart',
    JSON.stringify(
      cart
    )
  );


  localStorage.setItem(
    'venusDiscount',
    String(
      discount
    )
  );

}


function subtotal() {

  return cart.reduce(

    (
      sum,
      id
    ) => {

      const service =
        services.find(
          item =>
            item.id === id
        );


      return (

        sum +

        (
          service
            ? serviceData(
                service
              ).price

            : 0
        )

      );

    },

    0

  );

}


function total() {

  return subtotal() *
    (
      1 -
      discount
    );

}


function toast(
  text
) {

  const element =
    $('#toast');


  if (!element) {
    return;
  }


  element.textContent =
    text;


  element.classList.add(
    'show'
  );


  setTimeout(
    () => {

      element.classList.remove(
        'show'
      );

    },
    2200
  );

}


